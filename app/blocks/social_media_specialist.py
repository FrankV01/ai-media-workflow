"""
app.blocks.social_media_specialist — Social Media Specialist creative role

The Social Media Specialist receives the complete production dossier — every
report generated by the pipeline — and crafts platform-optimized social media
post suggestions for the generated assets.

She has access to:
- The generated images themselves — one downscaled image per variant,
  attached to the LLM call as vision content (requires a vision-capable
  profile model; capped by SOCIAL_MEDIA_MAX_IMAGES)
- The original creative brief (Art Director)
- The structured generation prompts (Prompt Architect)
- The generation results and file paths (Media Producer)
- The quality critique and verdict (Art Critic)

From these she produces a Markdown lead post followed by structured JSON:
one unified post suggestion written to work across all distribution
channels — social feeds and content licensing marketplaces alike.

The response contract is defined in code (SOCIAL_MEDIA_MARKDOWN_TEMPLATE +
SOCIAL_MEDIA_RESPONSE_SCHEMA) and appended to the resolved system prompt at
run time, so it applies to default and customized prompts alike. Any JSON
object embedded in a custom prompt is merged over the schema — official key
names always remain.

Input:  Full pipeline context (all *_output keys + generated_images,
        generation_metadata) — images attached as vision content
Output: context["brief"] — human-readable summary (Markdown + JSON)
        context["social_media_specialist_output"] — full marketing content
        context["social_media_posts"] — parsed list of post dicts

Suggested next role: None (terminal for now)
"""

from __future__ import annotations

import base64
import io
import logging
import os
from dataclasses import replace
from pathlib import Path
from typing import Any

from PIL import Image

from app.blocks.base import BlockMeta
from app.blocks.output_contract import (
    build_output_contract as _build_contract,
)
from app.blocks.output_contract import (
    extract_json_object,
)
from app.blocks.registry import register
from app.blocks.role_block import RoleBlock
from app.config import settings
from app.services.configuration.base import ResolvedLlmConfiguration

logger = logging.getLogger(__name__)

SOCIAL_MEDIA_SYSTEM_PROMPT = """\
You are a top-tier Content Strategist and Marketing Specialist for visual media. \
You understand audience engagement, channel conventions, and what makes visual \
assets discoverable and marketable.

You will receive a complete production dossier containing:
1. Images of the generated assets themselves — attached to this message; \
look at them and ground everything you write in what is actually visible
2. The original creative brief from the Art Director
3. The technical prompts used for image generation
4. A summary of the generated assets (including file paths)
5. A quality critique from the Art Critic

Your task is to create ONE unified post suggestion that works across all \
distribution channels — social feeds, microblogs, and content licensing \
marketplaces alike. Write it once, at its best: a descriptive, punchy title; \
a caption/description that is accurate to what the images visibly show and \
usable verbatim on a marketplace listing or a social post; and tags that \
work both as hashtags and as marketplace search keywords.

Guidelines:
- Describe only what the images actually show — visual accuracy is the \
foundation of both marketplace discoverability and honest marketing.
- Keep all metadata accurate and grounded in the visible content; do not add \
irrelevant or misleading keywords.
- Keep the content original and broadly usable: avoid naming real artists, \
brands, people, or copyrighted works; describe qualities generically.
- Use respectful, inclusive, non-profane language.

Be creative, authentic, and strategic.\
"""

SOCIAL_MEDIA_MARKDOWN_TEMPLATE = """\
## Markdown

**Title**: <content title — descriptive, punchy and attention-grabbing>
**Description**: <full post caption/body text, channel-appropriate length>
**Tags**: <hashtag or topic tag>, <hashtag or topic tag>, <etc>\
"""

SOCIAL_MEDIA_RESPONSE_SCHEMA: dict[str, Any] = {
    "posts": [
        {
            "platform": "unified",
            "title": "<content title — descriptive, punchy and attention-grabbing>",
            "description": (
                "<post caption/listing text — works verbatim on social feeds and marketplaces>"
            ),
            "tags": ["<hashtag or search keyword>", "..."],
        }
    ],
    "summary": "<1-2 sentence overview of the posting strategy>",
}


def build_output_contract(system_prompt: str) -> str:
    """Return the Social Media Specialist's Markdown + JSON response contract.

    SOCIAL_MEDIA_RESPONSE_SCHEMA: official key names always remain (they can't
    be removed or renamed), while user values may redefine them and extra user
    keys pass through.
    """
    return _build_contract(
        system_prompt,
        SOCIAL_MEDIA_RESPONSE_SCHEMA,
        markdown_example=SOCIAL_MEDIA_MARKDOWN_TEMPLATE,
    )


@register
class SocialMediaSpecialist(RoleBlock):
    """Creates platform-optimized social media post suggestions from production assets."""

    meta = BlockMeta(
        name="social_media_specialist",
        description=(
            "Creates platform-optimized social media posts from generated assets and reports"
        ),
        version="0.2.0",
        category="creative",
        inputs=[
            "brief",
            "art_director_output",
            "prompt_architect_output",
            "media_producer_output",
            "art_critic_output",
            "generated_images",
        ],
        outputs=["brief", "social_media_specialist_output", "social_media_posts"],
    )

    role_name = "social_media_specialist"
    role_title = "Marketing & Content Strategist"
    role_description = (
        "Crafts marketing content for social channels and content licensing "
        "platforms from generated assets and the full production dossier"
    )
    system_prompt = SOCIAL_MEDIA_SYSTEM_PROMPT
    suggested_next = None  # Terminal block for now
    appends_output_contract = True
    default_temperature = 0.7

    async def resolve_configuration(self, context: dict[str, Any]) -> ResolvedLlmConfiguration:
        """Resolve the profile, then append the Markdown + JSON response contract.

        The contract applies whether the prompt is the code default or a user
        customization, so the specialist's output stays parseable either way.
        """
        resolved = await super().resolve_configuration(context)
        return replace(
            resolved,
            system_prompt=resolved.system_prompt + build_output_contract(resolved.system_prompt),
        )

    def _select_vision_images(self, context: dict[str, Any]) -> list[str]:
        """Pick up to SOCIAL_MEDIA_MAX_IMAGES source files to attach.

        Prefers generation_metadata — one smallest file per variant (the 1x
        refined render; upscales add pixels, not content). Falls back to the
        smallest files in generated_images. Only existing files are kept.
        """
        cap = max(0, settings.social_media_max_images)
        if cap == 0:
            return []

        def smallest(paths: list[Any]) -> str | None:
            existing = [p for p in paths if isinstance(p, str) and Path(p).is_file()]
            if not existing:
                return None
            return min(existing, key=lambda p: os.path.getsize(p))

        picked: list[str] = []
        metadata = context.get("generation_metadata") or []
        for entry in metadata:
            if len(picked) >= cap:
                break
            if not isinstance(entry, dict):
                continue
            path = smallest(entry.get("image_paths") or [])
            if path and path not in picked:
                picked.append(path)

        if not picked:
            remaining = [
                p
                for p in (context.get("generated_images") or [])
                if isinstance(p, str) and Path(p).is_file() and p not in picked
            ]
            remaining.sort(key=lambda p: os.path.getsize(p))
            picked.extend(remaining[: cap - len(picked)])

        return picked

    def _encode_image(self, path: str) -> dict[str, Any] | None:
        """Downscale and base64-encode an image as an OpenAI image_url part."""
        try:
            with Image.open(path) as img:
                img.thumbnail((settings.social_media_image_max_edge,) * 2, Image.LANCZOS)
                if img.mode not in ("RGB", "L"):
                    img = img.convert("RGB")
                buffer = io.BytesIO()
                img.save(buffer, format="JPEG", quality=85)
            data_uri = "data:image/jpeg;base64," + base64.b64encode(buffer.getvalue()).decode(
                "ascii"
            )
            return {"type": "image_url", "image_url": {"url": data_uri}}
        except Exception as exc:
            logger.warning("SocialMediaSpecialist: skipping image %s (%s)", path, exc)
            return None

    def build_user_content(self, context: dict[str, Any], input_brief: str) -> tuple[Any, str]:
        """Attach downscaled variant images as vision content parts.

        The audit copy stays plain text — the dossier plus the list of
        attached file paths — so no base64 reaches the Message rows.
        """
        paths = self._select_vision_images(context)
        parts: list[dict[str, Any]] = []
        attached: list[str] = []
        for path in paths:
            part = self._encode_image(path)
            if part is not None:
                parts.append(part)
                attached.append(path)
        if not parts:
            return input_brief, input_brief
        api_content = [{"type": "text", "text": input_brief}] + parts
        audit_content = input_brief + "\n\n[Attached images: " + ", ".join(attached) + "]"
        return api_content, audit_content

    async def run(self, context: dict[str, Any]) -> dict[str, Any]:
        """Compile the full dossier and pass to the LLM for post suggestions."""
        # Compile all reports into a single dossier for the specialist
        dossier_parts = []

        art_director = context.get("art_director_output", "")
        if art_director:
            dossier_parts.append("=== ART DIRECTOR — CREATIVE BRIEF ===\n" + art_director)

        prompt_architect = context.get("prompt_architect_output", "")
        if prompt_architect:
            dossier_parts.append(
                "=== PROMPT ARCHITECT — GENERATION PROMPTS ===\n" + prompt_architect
            )

        media_producer = context.get("media_producer_output", "")
        if media_producer:
            dossier_parts.append("=== MEDIA PRODUCER — GENERATION RESULTS ===\n" + media_producer)

        # Include image file paths
        images = context.get("generated_images", [])
        if images:
            dossier_parts.append(
                "=== GENERATED ASSET FILES ===\n" + "\n".join(f"  • {p}" for p in images)
            )

        art_critic = context.get("art_critic_output", "")
        if art_critic:
            verdict = context.get("art_critic_verdict", "unknown")
            dossier_parts.append(
                f"=== ART CRITIC — QUALITY REVIEW (verdict: {verdict}) ===\n" + art_critic
            )

        dossier = "\n\n".join(dossier_parts)

        if not dossier.strip():
            dossier = context.get("brief", "No production dossier available.")

        # Override brief so the base RoleBlock sends the full dossier
        original_brief = context.get("brief")
        context["brief"] = dossier

        try:
            result = await super().run(context)
        finally:
            if original_brief is not None:
                context["brief"] = original_brief

        # Try to parse the structured posts from the LLM output
        raw_output = result.get("output_deliverable", "")
        posts = self._extract_posts(raw_output)
        result["social_media_posts"] = posts

        return result

    def _extract_posts(self, raw: str) -> list[dict]:
        """Extract the posts list from the LLM's JSON response."""
        data = extract_json_object(raw)
        if data is not None:
            posts = data.get("posts", [])
            return posts if isinstance(posts, list) else []

        logger.warning("SocialMediaSpecialist: could not parse posts JSON")
        return []
